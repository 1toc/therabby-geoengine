"""Build approximate display colors from official station photo atlases.

Requires Pillow on the development machine. Colors include roof/other atlas
pixels and are visual hints, not surveyed facade materials.
"""
import hashlib
import json
from pathlib import Path
from statistics import median
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
FOLDER = ROOT / 'data/derived/station-photo-pilot'
OUTPUT = ROOT / 'viewer/station-style-profiles.js'


def build():
    manifest = json.loads((FOLDER / 'stream-full.json').read_text(encoding='utf-8'))
    profiles = {}
    for item in manifest['photos']:
        raw = (FOLDER / item['jpeg']).read_bytes()
        if hashlib.sha256(raw).hexdigest() != item['sha256']:
            raise ValueError('Source image hash mismatch: ' + item['photo_id'])
        with Image.open(FOLDER / item['jpeg']) as image:
            image = image.convert('RGB')
            image.thumbnail((160, 160))
            pixels = [p for p in image.getdata() if max(p) > 35 and sum(p) > 110]
        if not pixels:
            raise ValueError('No usable pixels: ' + item['photo_id'])
        color = [round(median(p[i] for p in pixels)) for i in range(3)]
        # Saturation and luminance are kept restrained for a unified 3D view.
        gray = sum(color) / 3
        color = [max(75, min(190, round(gray * .35 + c * .65))) for c in color]
        seed = int(hashlib.sha256(item['building_ids'][0].encode()).hexdigest()[:8], 16)
        profiles[item['material']] = {'color': color, 'layout': seed % 3,
                                      'floor_m': [3.0, 3.2, 3.5][(seed // 3) % 3],
                                      'bay_m': [2.6, 3.2, 4.0][(seed // 9) % 3],
                                      'photo_id': item['photo_id'],
                                      'building_ids': item['building_ids']}
    if len(profiles) != len(manifest['photos']):
        raise ValueError('Duplicate material names')
    OUTPUT.write_text('// Generated by scripts/build_station_style_profiles.py; visual estimates.\n'
                      'export const stationStyleProfiles = '
                      + json.dumps(profiles, ensure_ascii=False, separators=(',', ':')) + ';\n',
                      encoding='utf-8')
    print(f'Wrote {len(profiles)} photo-based visual profiles to {OUTPUT}')


if __name__ == '__main__':
    build()
